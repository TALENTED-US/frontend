function fillTemplate(template, voice) {
  return template.replaceAll('{name}', voice.name).replaceAll('{symbol}', voice.symbol).replaceAll('{goal}', voice.goal)
}

function buildAdditionalMessages(level, status) {
  const parts = level === 5 ? LEVEL_FIVE_PARTS[status] : STANDARD_PARTS[status]
  const voice = LEVEL_VOICE[level] || LEVEL_VOICE[1]
  return parts.starts.flatMap((start) =>
    parts.ends.map((end) => `${fillTemplate(start, voice)} ${fillTemplate(end, voice)}`),
  )
}

export function getButtieMessages(level, status) {
  const normalizedLevel = Math.min(5, Math.max(1, Number(level) || 1))
  const normalizedStatus = ['danger', 'caution', 'stable'].includes(status) ? status : 'stable'
  return [
    ...PROVIDED_MESSAGES[normalizedLevel][normalizedStatus],
    ...buildAdditionalMessages(normalizedLevel, normalizedStatus),
  ]
}

export function pickButtieMessage(level, status, random = Math.random) {
  const messages = getButtieMessages(level, status)
  return messages[Math.floor(random() * messages.length)] || messages[0]
}
